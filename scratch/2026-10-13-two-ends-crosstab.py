def build_cosets(G):
    auts=automorphisms(G); autset=set(auts); inn=set(inn_auts(G))
    seen=set(); cosets=[]
    for a in auts:
        if a in seen: continue
        cos=set(compose(a,i) for i in inn); cosets.append(cos); seen|=cos
    return G,auts,autset,inn,cosets

# ---- (Sigma) split: homomorphic section Out->Aut = subgroup S<=Aut, |S|=|Out|, S∩Inn={id}, S*Inn=Aut
#      equivalently a transversal that is closed under composition.  Brute: search a set of
#      coset reps closed under multiplication.  Use subgroup-generation test:
def sigma_splits(G,auts,autset,inn,cosets):
    idm=tuple(range(G.n)); nOut=len(cosets)
    if nOut==1: return True  # trivial Out
    innset=set(inn); autlist=list(autset)
    # candidate complement elements: one per non-identity coset, any element of that coset.
    # A complement is a subgroup of order nOut meeting each coset once. Search subgroups of
    # Aut of order nOut that intersect Inn trivially and are transversal.
    # Brute over subgroups generated by picks is expensive; instead: a complement exists iff
    # the extension splits iff exists section. Equivalent: find subgroup H<=Aut with
    # H∩Inn={id} and |H|=nOut. We search by backtracking a transversal closed under mult.
    reps=[sorted(c) for c in cosets]
    id_coset=coset_of(idm,cosets)
    order=[c for c in range(nOut) if c!=id_coset]
    # assignment: choice[c] = chosen element (a tuple) of coset c; coset id_coset -> idm
    chosen={id_coset: idm}
    def mul_coset(a,b):  # coset index of compose(a,b)
        return coset_of(compose(a,b),cosets)
    # backtracking: pick element for each coset s.t. the chosen set stays mult-closed
    def bt(i):
        if i==len(order):
            return True
        c=order[i]
        for x in reps[c]:
            # tentative
            chosen[c]=x
            ok=True
            # check closure with all already-chosen (both orders)
            for d,y in list(chosen.items()):
                for (p,q) in ((x,y),(y,x)):
                    z=compose(p,q); zc=coset_of(z,cosets)
                    if zc in chosen and chosen[zc]!=z:
                        ok=False; break
                    # z's coset might not be chosen yet; that's fine (partial)
                if not ok: break
            if ok and bt(i+1):
                return True
            del chosen[c]
        return False
    return bt(0)

# ---- (Z) central ext: split iff exists complement to Z(K) in K = subgroup S, |S|=|K|/|Z|,
#      S∩Z={e}. For class-2 nonabelian this must FAIL.  couples iff K nonabelian.
def z_split_and_couple(G):
    Z=center(G); zset=set(Z); e=G.idx[G.e]
    nonab = any(G.T[a][b]!=G.T[b][a] for a in range(G.n) for b in range(G.n))
    couples = nonab  # [k,k']!=1 exists, lands in [K,K]<=Z(K) (class2), trivial center-action
    # splitting: complement subgroup of order n/|Z|
    target=G.n//len(Z)
    if len(Z)==1:
        return True, couples, nonab   # Z trivial -> ext trivial -> split
    if target==1:
        return True, couples, nonab   # Inn trivial (K abelian) -> complement {e} -> split
    # backtracking subgroup search meeting Z only at e, of size target
    # generate subgroups by closure of element subsets — brute but groups are small
    elems=[x for x in range(G.n) if x not in zset or x==e]
    def closure(gens):
        seen={e}; frontier=[e]
        while frontier:
            nf=[]
            for x in frontier:
                for g in list(seen):
                    for pr in (G.T[x][g],):
                        if pr not in seen: seen.add(pr); nf.append(pr)
                for g in gens:
                    y=G.T[x][g]
                    if y not in seen: seen.add(y); nf.append(y)
            frontier=nf
        return seen
    # try small generating sets
    cand=[x for x in range(G.n) if x!=e and x not in zset]
    # size up to 3 generators usually enough for these orders
    import itertools as it
    for r in range(1,4):
        for gens in it.combinations(cand,r):
            S=closure(gens)
            if len(S)==target and all((z==e or z not in S) for z in Z):
                return True, couples, nonab
            if len(S)>target*2 and r>=2:  # prune nothing specific; keep going
                pass
    return False, couples, nonab

def report(name,G):
    data=build_cosets(G)
    G,auts,autset,inn,cosets=data
    nOut=len(cosets)
    with contextlib.redirect_stdout(io.StringIO()):
        wit=witness_search(name,data,verbose=False)
    sig_split=sigma_splits(G,auts,autset,inn,cosets)
    zsplit,zcouple,nonab=z_split_and_couple(G)
    dcouple = len(wit)>0
    inn_ab = all(compose(a,b)==compose(b,a) for a in inn for b in inn)  # class<=2
    print(f"{name:10s} |K|={G.n:3d} |Z|={len(center(G)):2d} |Aut|={len(auts):4d} |Inn|={len(inn):3d} |Out|={nOut:3d} "
          f"| InnAb(cls<=2)={str(inn_ab):5s} | Sigma split={str(sig_split):5s} delta-couple={str(dcouple):5s} ({len(wit):2d}) "
          f"| Z split={str(zsplit):5s} g-couple={str(zcouple):5s}")
    return dict(name=name,dcouple=dcouple,zcouple=zcouple,sig_split=sig_split,zsplit=zsplit)

